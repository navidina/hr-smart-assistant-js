#!/usr/bin/env node
// Convert plist.xlsx into a D1 seed file (seed-employees.sql).
// Runs locally on your machine (Node.js) — it is NOT part of the deployed Worker.
//
// Usage:
//   node tools/import-employees.mjs [input.xlsx] [output.sql]
// Then load it into D1:
//   wrangler d1 execute smartassistant --remote --file=./seed-employees.sql

import { readFileSync, writeFileSync } from "node:fs";
import * as XLSX from "xlsx";

const inputPath = process.argv[2] || "plist.xlsx";
const outputPath = process.argv[3] || "seed-employees.sql";

// Persian column header keywords -> employee field (priority order matters so
// that e.g. "کد ملی" maps to national_id before "کد پرسنلی" maps to code).
const FIELD_KEYWORDS = [
  ["national_id", ["ملی"]],
  ["code", ["پرسنلی", "کد"]],
  ["mobile", ["موبایل", "همراه"]],
  ["extension", ["داخلی"]],
  ["hire_date", ["استخدام"]],
  ["birth_date", ["تولد"]],
  ["department", ["بخش"]],
  ["post", ["پست", "سمت"]],
  ["hoze", ["حوزه", "معاونت"]],
  ["name", ["خانوادگی", "نام"]],
];

const PERSIAN_DIGITS = {
  "۰": "0", "۱": "1", "۲": "2", "۳": "3", "۴": "4",
  "۵": "5", "۶": "6", "۷": "7", "۸": "8", "۹": "9",
  "٠": "0", "١": "1", "٢": "2", "٣": "3", "٤": "4",
  "٥": "5", "٦": "6", "٧": "7", "٨": "8", "٩": "9",
};

function normalizeHeader(h) {
  return String(h).replace(/‌/g, " ").replace(/\s+/g, " ").trim();
}

function normalizeMobile(input) {
  if (!input) return "";
  let s = String(input).trim().replace(/[۰-۹٠-٩]/g, (d) => PERSIAN_DIGITS[d] ?? d);
  s = s.replace(/[^\d+]/g, "");
  if (s.startsWith("+98")) s = "0" + s.slice(3);
  else if (s.startsWith("0098")) s = "0" + s.slice(4);
  else if (s.startsWith("98") && s.length === 12) s = "0" + s.slice(2);
  else if (s.startsWith("9") && s.length === 10) s = "0" + s;
  return /^09\d{9}$/.test(s) ? s : "";
}

function cell(value) {
  if (value === null || value === undefined) return "";
  if (value instanceof Date) return ""; // Jalali dates are expected as text
  return String(value).replace(/\.0$/, "").trim();
}

function sqlEscape(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function resolveColumns(headers) {
  const mapping = {};
  const used = new Set();
  for (const [field, keywords] of FIELD_KEYWORDS) {
    for (const header of headers) {
      if (used.has(header)) continue;
      const norm = normalizeHeader(header);
      if (keywords.some((kw) => norm.includes(kw))) {
        mapping[field] = header;
        used.add(header);
        break;
      }
    }
  }
  return mapping;
}

function main() {
  const workbook = XLSX.read(readFileSync(inputPath));
  const sheet = workbook.Sheets[workbook.SheetNames[0]];
  const rows = XLSX.utils.sheet_to_json(sheet, { defval: "" });
  if (!rows.length) {
    console.error("No rows found in", inputPath);
    process.exit(1);
  }

  const headers = Object.keys(rows[0]);
  const map = resolveColumns(headers);
  if (!map.code || !map.name) {
    console.error("Could not find required columns (code/name). Detected headers:", headers);
    console.error("Resolved mapping:", map);
    process.exit(1);
  }
  console.error("Resolved column mapping:", map);

  const fields = [
    "code", "name", "mobile", "extension", "department",
    "post", "hire_date", "birth_date", "hoze", "national_id",
  ];

  const seen = new Set();
  const statements = [];
  let skipped = 0;
  for (const row of rows) {
    const record = {};
    for (const field of fields) {
      const header = map[field];
      record[field] = header ? cell(row[header]) : "";
    }
    record.mobile = normalizeMobile(record.mobile);
    if (!record.code || !record.name) {
      skipped += 1;
      continue;
    }
    if (seen.has(record.code)) continue;
    seen.add(record.code);

    const values = fields.map((f) => sqlEscape(record[f])).join(", ");
    statements.push(
      `INSERT OR REPLACE INTO employees (${fields.join(", ")}) VALUES (${values});`,
    );
  }

  const sql = [
    "-- Generated by tools/import-employees.mjs",
    "BEGIN TRANSACTION;",
    ...statements,
    "COMMIT;",
    "",
  ].join("\n");

  writeFileSync(outputPath, sql, "utf8");
  console.error(`Wrote ${statements.length} employees to ${outputPath} (skipped ${skipped} incomplete rows).`);
}

main();
